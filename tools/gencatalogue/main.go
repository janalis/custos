// Command gencatalogue regenerates internal/inspection/catalogue/catalogue.go
// from the rule facts (internal/inspection/meta/rules.json and
// native-rules.json) and the rule packages (internal/inspection/rules/<id>).
// Run it with `go generate ./internal/inspection/catalogue` or
// `make rules-doc`.
//
// catalogue.All constructs inspections in group order, sorted by ID within
// each group; the order also decides which conflicting fixes come first.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/parser"
	"go/token"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// groups is the execution order of rule groups. A rule whose group is not
// listed here is rejected: place a new group explicitly.
var groups = []string{
	"Architecture",
	"Code style",
	"Compatibility",
	"Confusing constructs",
	"Control flow",
	"Language level migration",
	"Performance",
	"PHPUnit",
	"Probable bugs",
	"Security",
	"Type compatibility",
	"Unused",
}

// output is the generated file, relative to the repository root.
const output = "internal/inspection/catalogue/catalogue.go"

const modulePrefix = "github.com/janalis/custos/"

func main() { os.Exit(run(os.Args[1:], os.Stdout, os.Stderr)) }

// run writes the catalogue under -root (default: the current directory).
func run(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("gencatalogue", flag.ContinueOnError)
	fs.SetOutput(stderr)
	root := fs.String("root", ".", "repository root")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	src, n, err := generate(*root)
	if err == nil {
		err = os.WriteFile(filepath.Join(*root, output), src, 0o644)
	}
	if err != nil {
		fmt.Fprintln(stderr, "gencatalogue:", err)
		return 1
	}
	fmt.Fprintf(stdout, "catalogue: %d rules\n", n)
	return 0
}

type fact struct {
	ID    string `json:"id"`
	Group string `json:"group"`
}

type entry struct {
	fact
	rank int
	path string // import path
	name string // package name
}

// generate returns the gofmt-canonical catalogue source for the repository at
// root and the number of rules it constructs.
func generate(root string) ([]byte, int, error) {
	ranks := make(map[string]int, len(groups))
	for i, g := range groups {
		ranks[g] = i
	}
	var entries []entry
	for _, file := range []string{"rules.json", "native-rules.json"} {
		raw, err := os.ReadFile(filepath.Join(root, "internal", "inspection", "meta", file))
		if err != nil {
			return nil, 0, err
		}
		var facts []fact
		if err := json.Unmarshal(raw, &facts); err != nil {
			return nil, 0, fmt.Errorf("%s: %w", file, err)
		}
		for _, f := range facts {
			rank, ok := ranks[f.Group]
			if !ok {
				return nil, 0, fmt.Errorf("%s: rule %s has unknown group %q; add it to the group order in tools/gencatalogue", file, f.ID, f.Group)
			}
			dir := "internal/inspection/rules/" + strings.ToLower(f.ID)
			name, err := packageName(filepath.Join(root, filepath.FromSlash(dir), "rule.go"))
			if err != nil {
				return nil, 0, fmt.Errorf("rule %s: %w", f.ID, err)
			}
			entries = append(entries, entry{fact: f, rank: rank, path: modulePrefix + dir, name: name})
		}
	}
	sort.Slice(entries, func(i, j int) bool {
		if entries[i].rank != entries[j].rank {
			return entries[i].rank < entries[j].rank
		}
		return entries[i].ID < entries[j].ID
	})
	for i := 1; i < len(entries); i++ {
		if entries[i].ID == entries[i-1].ID {
			return nil, 0, fmt.Errorf("rule %s is listed twice", entries[i].ID)
		}
	}
	return render(entries), len(entries), nil
}

// packageName reads the package clause of a rule's rule.go.
func packageName(path string) (string, error) {
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.PackageClauseOnly)
	if err != nil {
		return "", err
	}
	return f.Name.Name, nil
}

// render writes the source directly in gofmt's canonical form.
func render(entries []entry) []byte {
	imports := []string{fmt.Sprintf("\t%q\n", modulePrefix+"internal/inspection/analysis")}
	for _, e := range entries {
		alias := ""
		if e.name != filepath.Base(e.path) {
			alias = e.name + " "
		}
		imports = append(imports, fmt.Sprintf("\t%s%q\n", alias, e.path))
	}
	// Import paths only differ after the shared prefix and contain no quote,
	// so sorting the lines without their aliases sorts them by path.
	sort.Slice(imports, func(i, j int) bool { return importPath(imports[i]) < importPath(imports[j]) })
	var b strings.Builder
	// The package comment lives in generate.go: linters skip generated files.
	b.WriteString("// Code generated by tools/gencatalogue from internal/inspection/meta; DO NOT EDIT.\n\n")
	b.WriteString("package catalogue\n\nimport (\n")
	for _, line := range imports {
		b.WriteString(line)
	}
	b.WriteString(")\n\n// All returns inspections in stable group and identifier order.\n")
	b.WriteString("func All() []analysis.Rule {\n\treturn []analysis.Rule{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t\t%s.New(),\n", e.name)
	}
	b.WriteString("\t}\n}\n")
	return []byte(b.String())
}

func importPath(line string) string { return line[strings.IndexByte(line, '"'):] }
