// The committed catalogue must be what the generator produces from the
// committed facts and rule packages; CI fails on a stale file.
func TestCatalogueIsCurrent(t *testing.T) {
	root := filepath.Join("..", "..")
	want, n, err := generate(root)
	if err != nil {
		t.Fatal(err)
	}
	if n == 0 {
		t.Fatal("no rules generated")
	}
	got, err := os.ReadFile(filepath.Join(root, output))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is stale; run `go generate ./internal/inspection/catalogue` (or `make rules-doc`)", output)
	}
	formatted, err := format.Source(want)
	if err != nil || !bytes.Equal(formatted, want) {
		t.Fatalf("generated catalogue is not gofmt-canonical: %v", err)
	}
}

func write(t *testing.T, path, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func fixture(t *testing.T, extracted, native string) string {
	t.Helper()
	root := t.TempDir()
	write(t, filepath.Join(root, "internal/inspection/meta/rules.json"), extracted)
	write(t, filepath.Join(root, "internal/inspection/meta/native-rules.json"), native)
	for dir, pkg := range map[string]string{"kettle": "kettle", "teapot": "teapot", "saucer": "saucer", "mug": "cup"} {
		write(t, filepath.Join(root, "internal/inspection/rules", dir, "rule.go"), "// Package "+pkg+" is a test rule.\npackage "+pkg+"\n")
	}
	if err := os.MkdirAll(filepath.Join(root, "internal/inspection/catalogue"), 0o755); err != nil {
		t.Fatal(err)
	}
	return root
}

func TestRun(t *testing.T) {
	root := fixture(t,
		`[{"id":"Teapot","group":"Unused"},{"id":"Saucer","group":"Code style"}]`,
		`[{"id":"Mug","group":"Unused"},{"id":"Kettle","group":"Architecture","severity":"info"}]`)
	var stdout, stderr bytes.Buffer
	if code := run([]string{"-root", root}, &stdout, &stderr); code != 0 {
		t.Fatalf("exit %d: %s", code, stderr.String())
	}
	if got := stdout.String(); got != "catalogue: 4 rules\n" {
		t.Errorf("stdout = %q", got)
	}
	got, err := os.ReadFile(filepath.Join(root, output))
	if err != nil {
		t.Fatal(err)
	}
	want := `// Code generated by tools/gencatalogue from internal/inspection/meta; DO NOT EDIT.

package catalogue

import (
	"github.com/janalis/custos/internal/inspection/analysis"
	"github.com/janalis/custos/internal/inspection/rules/kettle"
	cup "github.com/janalis/custos/internal/inspection/rules/mug"
	"github.com/janalis/custos/internal/inspection/rules/saucer"
	"github.com/janalis/custos/internal/inspection/rules/teapot"
)

// All returns inspections in stable group and identifier order.
func All() []analysis.Rule {
	return []analysis.Rule{
		kettle.New(),
		saucer.New(),
		cup.New(),
		teapot.New(),
	}
}
`
	if string(got) != want {
		t.Errorf("generated:\n%s", got)
	}
	if formatted, err := format.Source(got); err != nil || !bytes.Equal(formatted, got) {
		t.Errorf("not gofmt-canonical: %v", err)
	}
}

func TestRunErrors(t *testing.T) {
	ok := `[{"id":"Teapot","group":"Unused"}]`
	cases := []struct {
		name, extracted, native, want string
		setup                         func(root string)
	}{
		{name: "missing facts", want: "native-rules.json", setup: func(root string) {
			_ = os.Remove(filepath.Join(root, "internal/inspection/meta/native-rules.json"))
		}},
		{name: "malformed facts", native: `{`, want: "native-rules.json:"},
		{name: "unknown group", native: `[{"id":"Mug","group":"Teaware"}]`, want: `unknown group "Teaware"`},
		{name: "missing package", native: `[{"id":"Spoon","group":"Unused"}]`, want: "rule Spoon:"},
		{name: "duplicate", native: ok, want: "rule Teapot is listed twice"},
		{name: "unwritable output", native: `[]`, want: "catalogue.go", setup: func(root string) {
			_ = os.RemoveAll(filepath.Join(root, "internal/inspection/catalogue"))
		}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			extracted := tc.extracted
			if extracted == "" {
				extracted = ok
			}
			root := fixture(t, extracted, tc.native)
			if tc.setup != nil {
				tc.setup(root)
			}
			var stdout, stderr bytes.Buffer
			if code := run([]string{"-root", root}, &stdout, &stderr); code != 1 || !strings.Contains(stderr.String(), tc.want) {
				t.Fatalf("exit %d, stderr %q, want %q", code, stderr.String(), tc.want)
			}
		})
	}
	var stdout, stderr bytes.Buffer
	if code := run([]string{"-bogus"}, &stdout, &stderr); code != 2 {
		t.Fatalf("bad flag: exit %d", code)
	}
}
