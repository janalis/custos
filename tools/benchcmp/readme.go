//go:build unix

package main

import (
	"fmt"
	"strings"
)

const (
	readmeStart = "<!-- compare:start (generated by `make compare-doc` from bench/results.json and bench/features.json) -->"
	readmeEnd   = "<!-- compare:end -->"
	pageURL     = "https://janalis.github.io/custos/guide/benchmark"
)

// readmeSection is the README comparison: times on the largest project
// measured, then the features (none when f is nil), both in short.
func readmeSection(r *Results, f *Features) string {
	var b strings.Builder
	if c, found := largestCorpus(r); found {
		fmt.Fprintf(&b, "**Speed** on %s `%s` (%s PHP files), %d cores, median of %d runs:\n\n",
			repoLink(c.Repo), escape(c.Tag), thousands(c.Files), r.Runner.Cores, r.Runs)
		b.WriteString("| Tool | Kind | Time | Peak memory |\n| :--- | :--- | ---: | ---: |\n")
		for _, row := range sortedRows(c.Rows) {
			if row.Status != "ok" {
				fmt.Fprintf(&b, "| %s | %s | %s | — |\n", rowLabel(row), escape(row.Kind), escape(row.Status))
				continue
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", rowLabel(row), escape(row.Kind), seconds(row.Median), megabytes(row.PeakMB))
		}
		b.WriteString("\n")
	}
	if f != nil {
		b.WriteString("**Features** (✓ yes, ◐ partial, — no):\n\n")
		b.WriteString(f.compact())
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "Other projects, versions, finding counts and the sources of every feature are on the\n[benchmark page](%s).\n", pageURL)
	return b.String()
}

// largestCorpus is the corpus with the most files.
func largestCorpus(r *Results) (CorpusResult, bool) {
	var best CorpusResult
	for _, c := range r.Corpora {
		if c.Files > best.Files || best.Name == "" {
			best = c
		}
	}
	return best, best.Name != ""
}

// thousands writes n with comma separators.
func thousands(n int) string {
	s := fmt.Sprint(n)
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	return s
}

// spliceReadme replaces the generated section of readme with section.
func spliceReadme(readme, section string) (string, error) {
	start := strings.Index(readme, readmeStart)
	end := strings.Index(readme, readmeEnd)
	if start < 0 || end < start {
		return "", fmt.Errorf("no %q … %q section", readmeStart, readmeEnd)
	}
	return readme[:start+len(readmeStart)] + "\n\n" + section + "\n" + readme[end:], nil
}
