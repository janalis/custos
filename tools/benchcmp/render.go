//go:build unix

package main

import (
	"cmp"
	"fmt"
	"slices"
	"strings"
)

const repoURL = "https://github.com/janalis/custos"

// kindOrder sorts table rows: analyzers, then linters, then fixers.
var kindOrder = map[string]int{"analyzer": 0, "linter": 1, "fixer": 2}

// render writes the documentation page for r, with the feature comparison f
// (none when nil).
func render(r *Results, f *Features) string {
	var b strings.Builder
	b.WriteString("---\ntitle: Benchmark\neditLink: false\n---\n\n")
	b.WriteString("<!-- Generated by `make compare-doc` from bench/results.json — do not edit by hand. -->\n\n")
	b.WriteString("# Benchmark\n\n")
	b.WriteString("How long custos and other PHP tools take on real projects, and how much memory they\n")
	fmt.Fprintf(&b, "need. The [benchmark workflow](%s/actions/workflows/benchmark.yml) refreshes these\n", repoURL)
	b.WriteString("numbers every week, with the latest release of every tool and project.\n\n")
	b.WriteString("::: warning Different tools, different jobs\n")
	b.WriteString("Type checkers infer much more than custos, linters mostly check style, and fixers\n")
	b.WriteString("rewrite code. Compare times within a kind, and read finding counts only as a sign that\n")
	b.WriteString("a tool did its work: each counts what its own rules look for.\n:::\n\n")
	if len(r.Corpora) == 0 {
		b.WriteString("No results yet: they appear after the first run of the benchmark workflow.\n")
	} else {
		cpu := ""
		if r.Runner.CPU != "unknown" {
			cpu = r.Runner.CPU + ", "
		}
		fmt.Fprintf(&b, "Measured on %s on %s, %s%d cores, %.0f GB of memory, with PHP %s.\n",
			escape(r.Date), escape(r.Runner.OS), escape(cpu), r.Runner.Cores, r.Runner.MemoryGB, escape(r.PHP))
		fmt.Fprintf(&b, "Each time is the median of %d runs.\n", r.Runs)
	}
	for _, c := range r.Corpora {
		corpusTable(&b, c)
	}
	if f != nil {
		b.WriteString("\n## Features\n\n")
		b.WriteString("What each tool offers besides speed. A tool that lacks a feature may still get it\n")
		b.WriteString("from a third-party plugin; the table lists what the tool itself provides.\n\n")
		b.WriteString(f.table())
	}
	b.WriteString("\n## Method\n\n")
	b.WriteString("- Every tool analyzes the project's source directories with its own configuration\n")
	fmt.Fprintf(&b, "  from [`bench/configs`](%s/tree/develop/bench/configs), after the project's\n", repoURL)
	b.WriteString("  dependencies are installed, so that analyzers can resolve vendor symbols.\n")
	b.WriteString("- Each run starts from an empty cache, after a warm-up run that fills the\n")
	b.WriteString("  operating system's file cache. Tools use their default parallelism, or every\n")
	b.WriteString("  core when they have to be told.\n")
	b.WriteString("- Peak memory sums the resident memory of the tool's processes, including its\n")
	b.WriteString("  parallel workers.\n")
	b.WriteString("- Findings: problems reported by analyzers and linters, edits `custos fix` would\n")
	b.WriteString("  apply, and files other fixers would change. Fixers run in dry-run mode.\n")
	b.WriteString("- *vs custos* divides a tool's time by the time of the custos command of the\n")
	b.WriteString("  same kind (`custos analyse`, or `custos fix` for fixers).\n")
	fmt.Fprintf(&b, "- Run it yourself with `make compare`; the tools, versions and projects are listed\n  in [`bench/competitors.json`](%s/blob/develop/bench/competitors.json).\n", repoURL)
	return b.String()
}

func corpusTable(b *strings.Builder, c CorpusResult) {
	fmt.Fprintf(b, "\n## %s\n\n", escape(c.Name))
	fmt.Fprintf(b, "[%s](%s) at `%s`, %d PHP files.\n\n", escape(strings.TrimSuffix(strings.TrimPrefix(c.Repo, "https://github.com/"), ".git")), strings.TrimSuffix(c.Repo, ".git"), escape(c.Tag), c.Files)
	b.WriteString("| Tool | Kind | Version | Time | vs custos | Peak memory | Findings |\n")
	b.WriteString("| :--- | :--- | :--- | ---: | ---: | ---: | ---: |\n")
	rows := slices.Clone(c.Rows)
	slices.SortStableFunc(rows, func(x, y Row) int {
		return cmp.Or(cmp.Compare(kindOrder[x.Kind], kindOrder[y.Kind]), cmp.Compare(ok(x), ok(y)), cmp.Compare(x.Median, y.Median))
	})
	for _, r := range rows {
		label := escape(r.Label)
		if strings.HasPrefix(r.ID, "custos") {
			label = "**" + label + "**"
		}
		if r.Status != "ok" {
			fmt.Fprintf(b, "| %s | %s | %s | %s | — | — | — |\n", label, escape(r.Kind), escape(strings.TrimPrefix(r.Version, "v")), escape(r.Status))
			continue
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s | %d |\n",
			label, escape(r.Kind), escape(strings.TrimPrefix(r.Version, "v")), seconds(r.Median), ratio(r, c.Rows), megabytes(r.PeakMB), r.Findings)
	}
}

// ok sorts failed rows last.
func ok(r Row) int {
	if r.Status == "ok" {
		return 0
	}
	return 1
}

// ratio compares r with the custos command of its kind.
func ratio(r Row, rows []Row) string {
	ref := "custos"
	if r.Kind == "fixer" {
		ref = "custos-fix"
	}
	for _, x := range rows {
		if x.ID == ref && x.Status == "ok" && x.Median > 0 {
			switch q := r.Median / x.Median; {
			case q < 0.1:
				return fmt.Sprintf("%.2f×", q)
			case q < 10:
				return fmt.Sprintf("%.1f×", q)
			default:
				return fmt.Sprintf("%.0f×", q)
			}
		}
	}
	return "—"
}

func seconds(s float64) string {
	switch {
	case s < 10:
		return fmt.Sprintf("%.2f s", s)
	case s < 100:
		return fmt.Sprintf("%.1f s", s)
	}
	return fmt.Sprintf("%.0f s", s)
}

func megabytes(mb float64) string {
	if mb >= 1024 {
		return fmt.Sprintf("%.1f GB", mb/1024)
	}
	return fmt.Sprintf("%.0f MB", mb)
}

// escape keeps tool output from breaking the table or reaching Vue.
func escape(s string) string {
	return strings.NewReplacer("|", `\|`, "<", "&lt;", ">", "&gt;", "{", "&#123;", "}", "&#125;", "\n", " ").Replace(s)
}
