// Command rulesdoc regenerates docs/internals/rules.md: the migration status of every
// rule (spec written, EA conformance result from the last local run).
package main

import (
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"custos/internal/inspection/meta"
)

const (
	out        = "docs/internals/rules.md"
	statusFile = ".cache/ea/conformance.json"
)

// catalogue is a seam for tests: the rule facts are embedded.
var catalogue = meta.All

func main() { os.Exit(run(".", os.Stdout, os.Stderr)) }

// run writes root/docs/internals/rules.md from the catalogue, root/specs and
// the last conformance results (root/.cache/ea/conformance.json, then the
// current docs/internals/rules.md for rules not run this time).
func run(root string, stdout, stderr io.Writer) int {
	rules, err := catalogue()
	if err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	status := map[string]string{}
	if b, err := os.ReadFile(filepath.Join(root, statusFile)); err == nil {
		_ = json.Unmarshal(b, &status)
	}
	// Keep the last known status of rules not run this time (e.g. RULE= runs).
	prev := previousStatus(filepath.Join(root, out))
	for id, s := range prev {
		if _, ok := status[id]; !ok {
			status[id] = s
		}
	}

	byGroup := map[string][]meta.Rule{}
	var groups []string
	specs, pass := 0, 0
	for _, r := range rules {
		if _, ok := byGroup[r.Group]; !ok {
			groups = append(groups, r.Group)
		}
		byGroup[r.Group] = append(byGroup[r.Group], r)
		if hasSpec(root, r.ID) {
			specs++
		}
		if status[r.ID] == "pass" {
			pass++
		}
	}
	sort.Strings(groups)

	var b strings.Builder
	b.WriteString("# Rule migration status\n\n")
	b.WriteString("Generated by `make rules-doc` — do not edit by hand.\n\n")
	fmt.Fprintf(&b, "- Rules: **%d**\n- Specs written: **%d/%d**\n- EA conformance passing: **%d/%d**\n\n", len(rules), specs, len(rules), pass, len(rules))
	b.WriteString("Conformance: `pass` / `fail` / `pending` (not implemented) / `—` (not run).\n")
	for _, g := range groups {
		fmt.Fprintf(&b, "\n## %s\n\n| Rule | Severity | Default | Fix | Spec | EA conformance |\n| :--- | :--- | :---: | :---: | :---: | :---: |\n", g)
		for _, r := range byGroup[g] {
			def := yes(r.EnabledByDefault)
			if r.Experimental {
				def = "exp."
			}
			st := status[r.ID]
			if st == "" {
				st = "—"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s |\n", r.ID, r.Severity, def, yes(r.HasFix), yes(hasSpec(root, r.ID)), st)
		}
	}
	if err := os.WriteFile(filepath.Join(root, out), []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	fmt.Fprintf(stdout, "%s: %d rules, %d specs, %d passing\n", out, len(rules), specs, pass)
	return 0
}

func hasSpec(root, id string) bool {
	_, err := os.Stat(filepath.Join(root, "specs", id+".md"))
	return err == nil
}

func yes(b bool) string {
	if b {
		return "✓"
	}
	return ""
}

// previousStatus parses the conformance column of the current docs/internals/rules.md.
func previousStatus(path string) map[string]string {
	m := map[string]string{}
	b, err := os.ReadFile(path)
	if err != nil {
		return m
	}
	for _, line := range strings.Split(string(b), "\n") {
		cols := strings.Split(line, "|")
		if len(cols) < 8 || !strings.HasPrefix(strings.TrimSpace(cols[1]), "`") {
			continue
		}
		id := strings.Trim(strings.TrimSpace(cols[1]), "`")
		if s := strings.TrimSpace(cols[6]); s != "—" && s != "" {
			m[id] = s
		}
	}
	return m
}
