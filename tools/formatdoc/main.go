// Command formatdoc regenerates docs/guide/format-settings.md: every setting
// of the formatter's registry, grouped as the registry groups them, with its
// type, allowed values and description, and the value each preset gives it.
package main

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/janalis/custos/internal/format"
)

const out = "docs/guide/format-settings.md"

// presetOrder lists the presets as the page shows them: each one after the
// preset it builds on. A test keeps it in step with format.Presets.
var presetOrder = []string{"psr1", "psr12", "per", "symfony", "laravel", "drupal"}

func main() { os.Exit(run(".", os.Stdout, os.Stderr)) }

// run writes root/docs/guide/format-settings.md.
func run(root string, stdout, stderr io.Writer) int {
	if err := os.WriteFile(filepath.Join(root, out), []byte(render()), 0o644); err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	fmt.Fprintf(stdout, "format settings: %d settings, %d presets\n", len(format.Registry()), len(presetOrder))
	return 0
}

// render returns the page.
func render() string {
	plain := map[string]*format.Resolved{}
	risky := map[string]*format.Resolved{}
	for _, p := range presetOrder {
		// The names come from the registry: Resolve cannot fail on them.
		plain[p], _ = format.Resolve(p, false)
		risky[p], _ = format.Resolve(p, true)
	}
	var b strings.Builder
	b.WriteString(`---
title: Format settings
---

<!-- Generated by ` + "`make rules-doc`" + ` (tools/formatdoc) from internal/format — do not edit by hand. -->

# Format settings

Every setting of [` + "`custos format`" + `](./formatting), grouped by what it
lays out. Set them in the ` + "`format.settings`" + ` object of
[` + "`custos.json`" + `](./configuration#format), or for one run with
` + "`--set id=value`" + `; ` + "`custos format --show-config`" + ` prints the value each
one takes and where it comes from. A ` + "`keep`" + ` value leaves that part of
the layout as written.

Presets (the [Formatting guide](./formatting#presets) explains how to pick
one; ` + "`per`" + ` is the default):

`)
	for _, p := range presetOrder {
		fmt.Fprintf(&b, "- [`%s`](%s)\n", p, format.PresetReference(p))
	}
	b.WriteString(`
Risky settings change more than the layout and stay off unless allowed; in
the preset tables, a cell such as ` + "`false`, risky: `true`" + ` gives the value a
preset applies only when risky settings are allowed (` + "`--allow-risky`" + ` or ` + "`allowRisky`" + `).
`)
	var groups []string
	byGroup := map[string][]*format.Setting{}
	for _, d := range format.Registry() {
		if _, ok := byGroup[d.Group]; !ok {
			groups = append(groups, d.Group)
		}
		byGroup[d.Group] = append(byGroup[d.Group], d)
	}
	for _, g := range groups {
		fmt.Fprintf(&b, "\n## %s\n\n", strings.ToUpper(g[:1])+g[1:])
		b.WriteString("| Setting | Type | Values | Description |\n|---|---|---|---|\n")
		for _, d := range byGroup[g] {
			id := "`" + d.ID + "`"
			if d.Risky {
				id += " (risky)"
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", id, d.Kind, allowed(d), cell(d.Description))
		}
		b.WriteString("\nPreset values:\n\n| Setting |")
		for _, p := range presetOrder {
			fmt.Fprintf(&b, " `%s` |", p)
		}
		b.WriteString("\n|---|" + strings.Repeat("---|", len(presetOrder)) + "\n")
		for _, d := range byGroup[g] {
			fmt.Fprintf(&b, "| `%s` |", d.ID)
			for _, p := range presetOrder {
				v := value(d.Get(&plain[p].Settings))
				if r := value(d.Get(&risky[p].Settings)); d.Risky && r != v {
					v += ", risky: " + r
				}
				fmt.Fprintf(&b, " %s |", v)
			}
			b.WriteString("\n")
		}
	}
	return b.String()
}

// allowed describes the values a setting takes.
func allowed(d *format.Setting) string {
	switch d.Kind {
	case format.KindBool:
		return "`true`, `false`"
	case format.KindInt:
		return "integer, 0 or more"
	case format.KindList:
		return "list of " + codes(d.Values)
	}
	return codes(d.Values)
}

// value renders a setting value as configuration writes it.
func value(v any) string {
	if l, ok := v.([]string); ok {
		if len(l) == 0 {
			return "`[]`"
		}
		return codes(l)
	}
	return "`" + fmt.Sprint(v) + "`"
}

func codes(items []string) string {
	quoted := make([]string, len(items))
	for i, it := range items {
		quoted[i] = "`" + it + "`"
	}
	return strings.Join(quoted, ", ")
}

// cell escapes the table separator in text.
func cell(text string) string { return strings.ReplaceAll(text, "|", `\|`) }
